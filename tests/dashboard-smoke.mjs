import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {withBrowser,delay} from './browser-driver.mjs';
process.loadEnvFile('.env');
const key=process.env.DEMO_API_KEY;
assert(key,'Falta la clave local');
const api=async(path)=>{
  const response=await fetch(`http://127.0.0.1:5173/api/${path}`,{headers:{'X-API-Key':key}});
  assert.equal(response.status,200);return response.json();
};
const format=value=>new Intl.NumberFormat('es-HN',{minimumFractionDigits:2,maximumFractionDigits:2}).format(Number(value));
const report={status:'running',tests:[],simulations:[]};
await withBrowser(async({call,evaluate,wait,click,setValue,screenshot,errors})=>{
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1050,deviceScaleFactor:1,mobile:false});
  await call('Page.navigate',{url:'http://127.0.0.1:5173/'});
  await wait('!!document.querySelector("#demo-key")','pantalla de acceso');
  await evaluate('document.querySelector("#demo-key").focus()');
  await call('Input.insertText',{text:'clave-incorrecta'});
  await delay(100);
  await click('#access-form button');
  await wait('!!document.querySelector("[role=alert]")','rechazo de clave incorrecta');
  report.tests.push('Clave incorrecta rechazada sin mostrar datos');
  await evaluate('document.querySelector("#demo-key").focus();document.querySelector("#demo-key").select()');
  await call('Input.insertText',{text:key});
  await delay(100);
  await click('#access-form button');
  await wait('document.querySelectorAll("[data-kpi]").length===5 && document.querySelectorAll(".recharts-surface").length>=2','cinco KPIs y gráficos reales');
  const initialFilters=await evaluate('({start:document.querySelector("#date-start").value,end:document.querySelector("#date-end").value})');
  const initial=await api(`dashboard?${new URLSearchParams(initialFilters)}`);
  assert((await evaluate('document.querySelector("[data-kpi=sales]").innerText')).includes(format(initial.kpis.sales)));
  report.initial_kpis=initial.kpis;
  report.tests.push('Cinco KPIs renderizados; importe coincide con API; gráficos visibles');
  await screenshot('day2-dashboard.png');

  const product=initial.products[0].id;
  const category=(await api(`breakdown?dimension=customer_category&product_id=${product}&start=2016-03-01&end=2016-05-31`)).items[0].id;
  const filtered=await api(`kpis?product_id=${product}&category_id=${category}&start=2016-03-01&end=2016-05-31`);
  await setValue('#date-start','2016-03-01');await setValue('#date-end','2016-05-31');
  await setValue('#product-id',String(product));await setValue('#category-id',String(category));
  await click('#filter-form button[type=submit]');
  await wait(`document.querySelector('[data-kpi=sales]')?.innerText.includes(${JSON.stringify(format(filtered.sales))})`,'filtros de fecha/producto/categoría aplicados');
  report.tests.push('Filtros temporales y dos dimensiones actualizan KPI conforme a API');
  await screenshot('day2-filtered.png');
  await click('[data-product-drill]');
  await wait('!!document.querySelector("[data-testid=detail-panel] tbody tr")','drill-down a líneas de producto');
  assert.equal(await evaluate('document.querySelector("#product-id").value'),String(product));
  report.tests.push('Navegación de producto desde resumen a detalle conservando filtros');
  await setValue('#product-id','');await setValue('#category-id','');await click('#filter-form button[type=submit]');
  await wait('!!document.querySelector("[data-testid=detail-panel] tbody tr")','detalle sin filtros dimensionales');
  const first=await evaluate('document.querySelector("[data-testid=detail-panel] tbody tr").innerText');
  await click('[data-action=next-page]');
  await wait(`document.querySelector('[data-testid=detail-panel] tbody tr')?.innerText!==${JSON.stringify(first)} && !!document.querySelector('[data-testid=detail-panel] tbody tr')`,'segunda página distinta');
  assert((await evaluate('document.querySelector(".pagination").innerText')).includes('Página 2'));
  report.tests.push('Paginación real con cambio de líneas y página 2');
  await screenshot('day2-detail.png');

  await click('[data-tab=summary]');
  await wait('!!document.querySelector("[data-category-drill]")','resumen disponible');
  const chosen=await evaluate('document.querySelector("[data-category-drill]").dataset.categoryDrill');
  await click('[data-category-drill]');
  await wait('!!document.querySelector("[data-testid=detail-panel] tbody tr")','drill-down de categoría');
  assert.equal(await evaluate('document.querySelector("#category-id").value'),chosen);
  report.tests.push('Navegación desde categoría de cliente a detalle');
  await click('[data-tab=operations]');
  await wait('!!document.querySelector("[data-testid=operations-panel] table tbody tr")','ejecuciones y calidad');
  if(await evaluate('!!document.querySelector("[data-testid=operations-panel] table button.text-action")')) {
    await click('[data-testid=operations-panel] table button.text-action');
    await wait('!!document.querySelector("[data-testid=rejection-detail] tbody tr")','detalle paginado de rechazo');
    report.tests.push('Monitoreo con ejecuciones, watermark y detalle real de cuarentena');
  } else {
    assert(await evaluate('document.querySelector("[data-testid=operations-panel]").innerText.includes("No hay rechazos registrados.")'));
    report.tests.push('Monitoreo con ejecuciones, watermark y ausencia explícita de rechazos en instalación limpia');
  }
  await screenshot('day2-operations.png');

  await click('[data-tab=summary]');
  await setValue('#date-start','2020-01-01');await setValue('#date-end','2020-01-31');
  await setValue('#product-id','');await setValue('#category-id','');await click('#filter-form button[type=submit]');
  await wait('!!document.querySelector("[data-testid=empty-state]")','período sin datos');
  report.tests.push('Ausencia de datos explícita fuera de cobertura');
  await screenshot('day2-empty.png');
  await click('[data-action=reset-filters]');
  await wait('document.querySelectorAll("[data-kpi]").length===5 && !document.querySelector("[data-testid=empty-state]")','restablecimiento de filtros');

  await evaluate(`window.__realFetch=window.fetch.bind(window);window.fetch=(...args)=>String(args[0]).includes('/api/dashboard')?new Promise(resolve=>setTimeout(()=>resolve(new Response(JSON.stringify({detail:'Error simulado de verificación visual'}),{status:503,headers:{'Content-Type':'application/json'}})),800)):window.__realFetch(...args)`);
  await click('[data-action=refresh]');
  await wait('!!document.querySelector("[role=status]")','estado de carga durante retraso simulado');
  await wait('document.querySelector("[role=alert]")?.innerText.includes("Error simulado")','estado de error explícito');
  report.simulations.push('Intercepción local de fetch: retraso 800 ms y HTTP 503; SQL Server no se detuvo ni se modificó.');
  await screenshot('day2-error-simulated.png');
  await evaluate('window.fetch=window.__realFetch;delete window.__realFetch');
  await click('[role=alert] button');
  await wait('document.querySelectorAll("[data-kpi]").length===5 && !document.querySelector("[role=alert]")','recuperación visual con datos reales');
  report.tests.push('Carga/error simulados identificados; reintento recupera consulta real');

  await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
  await evaluate('window.scrollTo(0,0)');await delay(500);
  assert(await evaluate('document.documentElement.scrollWidth<=window.innerWidth+1'),'Desbordamiento horizontal en móvil');
  await screenshot('day2-mobile.png',false);
  report.tests.push('Vista móvil 390 px sin desbordamiento horizontal');
  await evaluate("Array.from(document.querySelectorAll('.filter-shortcuts button')).find(b=>b.textContent.includes('Todo el histórico')).click()");
  const full=await api('kpis');
  await wait(`document.querySelector('[data-kpi=sales]')?.innerText.includes(${JSON.stringify(format(full.sales))})`,'histórico completo en móvil');
  await call('Emulation.setDeviceMetricsOverride',{width:360,height:800,deviceScaleFactor:1,mobile:true});
  await delay(350);
  assert(await evaluate('document.documentElement.scrollWidth<=window.innerWidth+1'),'Desbordamiento con importe histórico completo a 360 px');
  report.tests.push('Importe histórico completo y diseño a 360 px sin desbordamiento');
  await click('[data-tab=detail]');
  await wait('!!document.querySelector("[data-testid=detail-panel] tbody tr")','detalle móvil');
  assert(await evaluate('document.documentElement.scrollWidth<=window.innerWidth+1'),'Tabla de detalle desborda página móvil');
  await click('[data-tab=operations]');
  await wait('!!document.querySelector("[data-testid=operations-panel] table tbody tr")','operación móvil');
  assert(await evaluate('document.documentElement.scrollWidth<=window.innerWidth+1'),'Monitoreo desborda página móvil');
  report.tests.push('Tablas de detalle y monitoreo contenidas en móvil');
  assert.equal(errors.length,0,errors.join('\n'));
  report.javascript_errors=errors;
  report.status='passed';
});
await writeFile('documentation/evidence/dashboard-browser.json',JSON.stringify(report,null,2));
console.log(`Dashboard validado: ${report.tests.length} comprobaciones; simulación de error declarada; capturas guardadas.`);
